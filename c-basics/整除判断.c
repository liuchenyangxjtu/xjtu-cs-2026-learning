#include<stdio.h>

int main()
{
	int n=0;

	printf("请输入一个整数：");
	scanf("%d",&n);

	/*易错点1：判断相等是==，不是=。写成n%3=0是赋值，条件永远不成立*/
	if(n%3==0 && n%5==0){
		printf("%d能同时被3和5整除\n",n);
	}

	if(n%3==0){
		printf("%d能被3整除\n",n);
	}

	if(n%5==0){
		printf("%d能被5整除\n",n);
	}

	/*易错点2：同时整除要用&&，用||就变成"或"了*/
	/*易错点3：if后面只有一条语句时大括号可以省，但建议都加上，以后加语句不容易出错*/
	if(n%3!=0 && n%5!=0){
		printf("%d既不能被3整除也不能被5整除\n",n);
	}

	return 0;
}
