#include<stdio.h>

int main()
{
	int year=0;

	printf("请输入一个年份：");
	scanf("%d",&year);

	/*易错点1：括号不能省。&&比||优先级高，不加括号结果虽然对，但看不懂谁先算*/
	/*易错点2：一定要拿1900试一下！它能被4整除，但也能被100整除，所以不是闰年*/
	/*易错点3：不等于写!=，不是=!=，C里也没有<>这个符号*/
	if((year%4==0 && year%100!=0) || year%400==0){
		printf("%d年是闰年，2月有29天\n",year);
	}
	else{
		printf("%d年不是闰年，2月有28天\n",year);
	}

	/*易错点4：if-else只会走一个分支。别写成两个并列的if，那样可能都执行也可能都不执行*/

	return 0;
}
